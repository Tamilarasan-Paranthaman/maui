namespace Microsoft.Maui
{
    /// <summary>
    /// Defines the size variants for a <see cref="IFloatingActionButton"/>.
    /// </summary>
    public enum FabSize
    {
        /// <summary>
        /// Standard FAB size (56dp).
        /// </summary>
        Normal,

        /// <summary>
        /// Mini FAB size (40dp).
        /// </summary>
        Mini,

        /// <summary>
        /// Extended FAB with variable width to accommodate text and icon.
        /// </summary>
        Extended
    }
}
