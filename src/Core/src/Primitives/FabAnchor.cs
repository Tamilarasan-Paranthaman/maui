namespace Microsoft.Maui
{
    /// <summary>
    /// Defines the anchor position for a <see cref="IFloatingActionButton"/>.
    /// </summary>
    public enum FabAnchor
    {
        /// <summary>
        /// Anchored to the bottom-right corner of the parent.
        /// </summary>
        BottomRight,

        /// <summary>
        /// Anchored to the bottom-center of the parent.
        /// </summary>
        BottomCenter,

        /// <summary>
        /// Anchored to the bottom-left corner of the parent.
        /// </summary>
        BottomLeft,

        /// <summary>
        /// Anchored to the top-right corner of the parent.
        /// </summary>
        TopRight,

        /// <summary>
        /// Anchored to the top-left corner of the parent.
        /// </summary>
        TopLeft
    }
}
